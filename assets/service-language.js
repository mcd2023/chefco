    const ui = document.querySelectorAll("[data-ui]");
    const controls = document.querySelectorAll(".service-language [data-lang]");
    const copy = translations[document.body.dataset.service];

    function apply(language) {
        const index = languages.indexOf(language);
        if (index < 0) return;
        document.documentElement.lang = language;
        document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
        ui.forEach(element => {
            const key = element.dataset.ui;
            const values = key.startsWith("service:") ? translations[key.slice(8)].heading : copy[key] || common[key];
            if (values) element.textContent = values[index];
        });
        controls.forEach(control => {
            const attribute = control.tagName === "BUTTON" ? "aria-pressed" : "aria-current";
            control.setAttribute(attribute, String(control.dataset.lang === language));
        });
    }

    controls.forEach(control => {
        if (control.tagName === "BUTTON") control.addEventListener("click", () => apply(control.dataset.lang));
    });
    const preferred = window.merciLanguage.read();
    if (preferred !== document.documentElement.lang) apply(preferred);
